// The language names are shown in their own language, so anyone can find theirs.
window.LANGS = [["id", "Bahasa Indonesia"], ["en", "English"]];

// First guess before Rust answers: ?lang= in tests, else the WebView's language.
window.setLang = function setLang(lang) {
  const code = window.STRINGS_BY_LANG[lang] ? lang : "en";
  window.LANG = code;
  window.STRINGS = window.STRINGS_BY_LANG[code];
  document.documentElement.lang = code;
  return code;
};
window.setLang(new URLSearchParams(location.search).get("lang") || ((navigator.language || "").toLowerCase().startsWith("id") ? "id" : "en"));

window.t = function t(key, vars) {
  let s = window.STRINGS[key] ?? window.STRINGS_BY_LANG.en[key] ?? key;
  for (const [k, v] of Object.entries(vars || {})) s = s.replaceAll(`{${k}}`, String(v));
  return s;
};
